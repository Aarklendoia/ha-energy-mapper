/** Translation function for a Home Assistant language ("fr", "fr-CA", "en-GB"...). */
export function translator(language: string | undefined): Translate {
  const base = (language ?? "en").toLowerCase().split(/[-_]/)[0];
  const table = TABLES[base] ?? en;
  return (key, params) => {
    let text = table[key] ?? en[key] ?? key;
    if (params) for (const [k, v] of Object.entries(params)) text = text.replaceAll(`{${k}}`, v);
    return text;
  };
}
